// Computes an aligned road-grid route from (x1,z1) to (x2,z2)
export function computeRoadRoute(
  x1: number,
  z1: number,
  x2: number,
  z2: number
): Array<{ x: number; z: number }> {
  const snap = (v: number) => Math.max(-240, Math.min(320, Math.round(v / 80) * 80));
  const sx = snap(x1);
  const sz = snap(z1);
  const ex = snap(x2);
  const ez = snap(z2);

  const pts: Array<{ x: number; z: number }> = [{ x: x1, z: z1 }];
  if (Math.hypot(x1 - sx, z1 - sz) > 12) {
    pts.push({ x: sx, z: sz });
  }
  if (sx !== ex) {
    pts.push({ x: ex, z: sz });
  }
  if (sz !== ez) {
    pts.push({ x: ex, z: ez });
  }
  if (Math.hypot(ex - x2, ez - z2) > 8) {
    pts.push({ x: x2, z: z2 });
  }
  return pts;
}
